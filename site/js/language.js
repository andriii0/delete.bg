const preferenceKey = "delete.bg.language";
const selector = document.getElementById("language");
let language = navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
function readPreference() {
  try {
    const saved = localStorage.getItem(preferenceKey);
    if (saved === "en" || saved === "ru") language = saved;
  } catch {
    /* The selector still works when browser storage is disabled. */
  }
}

export function translate(key, values = {}) {
  const template =
    language === "ru" && Object.hasOwn(russian, key) ? russian[key] : key;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = values[name];
    if (typeof value === "number")
      return value.toLocaleString(language, { maximumFractionDigits: 1 });
    return value ?? match;
  });
}

// Keep the original text nodes so switching languages preserves icons, controls and canvas state.
const labels = [];
const walker = document.createTreeWalker(
  document.documentElement,
  NodeFilter.SHOW_TEXT,
);
while (walker.nextNode()) {
  const node = walker.currentNode;
  const key = node.data.trim().replace(/\s+/g, " ");
  if (!Object.hasOwn(russian, key)) continue;
  const prefix = node.data.match(/^\s*/)[0],
    suffix = node.data.match(/\s*$/)[0];
  labels.push(() => {
    node.data = prefix + translate(key) + suffix;
  });
}
for (const attr of ["title", "aria-label", "alt", "content"]) {
  for (const element of document.querySelectorAll("[" + attr + "]")) {
    const key = element.getAttribute(attr);
    if (Object.hasOwn(russian, key))
      labels.push(() => element.setAttribute(attr, translate(key)));
  }
}

const liveLabels = new Map();
export function showText(element, text) {
  const render = typeof text === "function" ? text : () => translate(text);
  liveLabels.set(element, render);
  element.textContent = render();
}
function apply() {
  document.documentElement.lang = language;
  selector.value = language;
  for (const update of labels) update();
  for (const [element, render] of liveLabels) element.textContent = render();
}
selector.addEventListener("change", () => {
  language = selector.value;
  try {
    localStorage.setItem(preferenceKey, language);
  } catch {}
  apply();
});
function restorePreference() {
  readPreference();
  apply();
}
window.addEventListener("pageshow", (event) => {
  if (event.persisted) restorePreference();
});
window.addEventListener("storage", (event) => {
  if (event.key === preferenceKey) restorePreference();
});
restorePreference();
